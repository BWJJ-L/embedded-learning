#ifndef __APP_H__
#define __APP_H__

#include "gpio_cfg.h"

// ======= 包含驱动头文件
#include "bsp_led188.h"
#include "bsp_adkey.h"
#include "bsp_ec12.h"
#include "bsp_ws2812.h"

// =====================================================================
// 考试参数（以评分表为准）
//
// 说明：考试2.md 的 PRD 与「考试内容」/评分表 有三处冲突，
//       按用户拍板的结论，一律以评分表为准：
//         温度上限 190（不是 PRD 的 200）
//         时间单位 秒（不是 PRD 的分钟）
//         默认时间 10 秒（不是 PRD 的 10 分钟）
//       要改回 PRD 口径，只改下面这几个宏即可，业务代码不用动。
// =====================================================================

// 温度：80 ~ 190 度，步长 5 度，默认 100 度
#define FRYER_TEMP_MIN        80
#define FRYER_TEMP_MAX        190
#define FRYER_TEMP_STEP       5
#define FRYER_TEMP_DEFAULT    100

// 时间：1 ~ 60 秒，步长 1 秒，默认 10 秒
#define FRYER_TIME_MIN        1
#define FRYER_TIME_MAX        60
#define FRYER_TIME_STEP       1
#define FRYER_TIME_DEFAULT    10

// =====================================================================
// 编码器：转一格算几个脉冲
//
// 判向已改成正交状态机（bsp_ec12.c），A、B 两相都进中断，
// 一个完整正交周期（转一格）会产生 **4 个合法单步**：
//     右转 0 -> 2 -> 3 -> 1 -> 0   每步 +1，共 +4
//     左转 0 -> 1 -> 3 -> 2 -> 0   每步 -1，共 -4
// 所以这里必须是 4，才是"转一格走 1 步"。
//
// 历史：老驱动只在 A 相边沿判向，一转一格只有 2 个脉冲，
// 这里曾写 2。改成正交状态机后若仍写 2，转一格会跳 2 步。
//
// 真机手感不合适时按倍数调：转一格走 2 步 -> 改成 8；转两格走 1 步 -> 改成 2。
// =====================================================================
// 按判向方案自动取值，不要手填 —— 手填最容易和驱动方案配错。
//   老方案（EC12_USE_QUADRATURE=0）：一转一格 2 脉冲。
//       取 1 => 转一格走 2 步（用户实测手感正常，容错翻倍）
//       取 2 => 转一格走 1 步（但余量为零，抖动时会"转两次才动"）
//   新方案（EC12_USE_QUADRATURE=1）：一转一格 4 脉冲，必须取 4。
#if EC12_USE_QUADRATURE
#define EC12_PULSES_PER_STEP  4
#else
#define EC12_PULSES_PER_STEP  1
#endif

// =====================================================================
// 任务周期（单位 ms，时基来自 TIMER5 的 1ms 中断）
// =====================================================================

// 数码管动态扫描：2ms 一位 × 5 位 = 10ms 一轮 = 100Hz，人眼无闪烁
#define LED188_SCAN_MS        2

// ADKey：内部是「每 1ms 采 1 次、累加 50 次出一帧」，所以必须 1ms 调用
#define ADKEY_SCAN_MS         1

// 按键/编码器消费、业务状态机
#define KEY_SCAN_MS           10
#define FRYER_TASK_MS         10

// WS2812 刷新（参考驱动的注释也是 40ms）
#define WS2812_REFRESH_MS     40

// =====================================================================
// WS2812 亮度
//
// 驱动的 WS2812_set_color_brightness(index, color, brightness) 里：
//   brightness 取值 0~100，100 = 满亮度。
// 这里按用户要求取 10（即满亮度的 10%）。
// =====================================================================
#define FRYER_LED_BRIGHTNESS  10

// =====================================================================
// 显示模式
//   温度模式：闪电标志亮，数码管显示温度
//   时间模式：百分号标志亮，数码管显示时间
// =====================================================================
typedef enum {
	FRYER_MODE_TEMP = 0,   // 温度模式
	FRYER_MODE_TIME = 1,   // 时间模式
} FryerMode_t;

// =====================================================================
// 业务状态（定义在 App_fryer.c）
// =====================================================================
extern uint8_t     g_power_on;    // 0 关机，1 开机
extern uint8_t     g_running;     // 0 暂停/待机，1 运行（加热中）
extern FryerMode_t g_mode;        // 当前显示模式
extern uint16_t    g_temp;        // 设定温度
extern uint16_t    g_time_set;    // 设定时间
extern uint16_t    g_time_left;   // 剩余时间，时间模式显示的就是它

// 编码器脉冲计数：中断里累加，任务里取走
extern volatile int32_t g_ec12_pulse;

// =====================================================================
// WS2812 颜色，格式 0x00RRGGBB
//
// 注意驱动的发送顺序是 G -> R -> B（不是 RGB），但入参仍是 0xRRGGBB，
// 转换在 bsp_ws2812.c 内部完成，业务层不用管。
// 放在 App.h 是因为 App_init 里也要用 COLOR_OFF 清场。
// =====================================================================
#define COLOR_HEAT   0xff0000u   // 红：加热中
#define COLOR_IDLE   0x00ff00u   // 绿：停止
#define COLOR_OFF    0x000000u   // 灭：关机

// =====================================================================
// 业务动作
// =====================================================================
void App_fryer_power_toggle(void);         // KEY3 长按：开关机
void App_fryer_mode_toggle(void);          // KEY1 点击：温度/时间切换
void App_fryer_run_toggle(void);           // KEY2 点击：运行/暂停
void App_fryer_value_add(int32_t step);    // 编码器旋转，正数加、负数减

// 4 颗彩灯统一设成同一个颜色（内部按 FRYER_LED_BRIGHTNESS 缩放）
void App_fryer_led_set(uint32_t color);

// =====================================================================
// 业务任务（无参无返回，供 Task.c 的函数指针表调用）
// =====================================================================
void App_led188_scan_task(void);   // LED188_SCAN_MS
void App_adkey_scan_task(void);    // ADKEY_SCAN_MS
void App_key_scan_task(void);      // KEY_SCAN_MS
void App_fryer_task(void);         // FRYER_TASK_MS
void App_ws2812_task(void);        // WS2812_REFRESH_MS

// =====================================================================
// 初始化
// =====================================================================
static inline void App_init(void) {
	LED188_init();     // 数码管（驱动内部会点亮测试内容）
	ADKey_init();      // ADKey 按键
	EC12_init();       // 旋转编码器
	WS2812_init();     // 彩灯

	// 上电默认是关机状态，所以要把驱动自检留下的内容清掉：
	//   数码管驱动会先点亮 123；彩灯驱动的 WS2812_init 里也可能留了测试色。
	// 不清的话，关机态却亮着灯，和评分表「长按开机才点亮」冲突。
	LED188_clear();
	App_fryer_led_set(COLOR_OFF);   // 彩灯置灭
	WS2812_display();               // 立刻刷一次，不用等 40ms 的刷新任务
}

#endif
