#include "App.h"

// =====================================================================
// 串口0接收回调
//
// USART0.h 里 USART0_RECV_CALLBACK 是 1，所以这个函数必须定义，
// 否则链接会报未解析符号。考试本身不用串口，这里只打印收到的第一个字节，
// 方便联调时观察板子是否活着。
// =====================================================================
void USART0_on_recv(uint8_t* data, uint32_t len) {
	if (len == 0) return;
	printf("recv[%d]:%#x\n", len, data[0]);
}
